# Day 2 Python Program
     
    ## This program demonstrates how to use variables in Python (by printing a name)...

name = "Krishna"                        #String variable
print("My name is", name)



age = 20                                #Integer variable
print("I am", age, "years old")



height = 6.1                            #Float variable     
print("My height is", height, "feet")



is_student = True                       #Boolean variable
print("I am a student:", is_student)



#character variable (Python does not have a specific char type, so we use a string of length 1)
char_var = "A"
print("This character is", char_var)